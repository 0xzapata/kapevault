// Writes src/app/features/autofill/public-suffixes.ts from the Public Suffix List, so autofill knows
// that evil.pages.dev and example.pages.dev are two different sites (pages.dev is a public suffix) while
// accounts.google.com and mail.google.com are one. Both sections are kept: ICANN (co.uk, me.uk) and
// PRIVATE (github.io, pages.dev, vercel.app, blogspot.com). No npm package: the list is data.
//
//   node scripts/public-suffix-sync.mjs                 download it from publicsuffix.org
//   node scripts/public-suffix-sync.mjs --from <file>   use a copy already downloaded
//
// Run it now and then (the list changes weekly; a stale list only misses the newest hosting suffixes).
import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const SOURCE = "https://publicsuffix.org/list/public_suffix_list.dat";
const here = path.dirname(url.fileURLToPath(import.meta.url));
const target = path.join(here, "..", "src", "app", "features", "autofill", "public-suffixes.ts");

const from = process.argv.indexOf("--from");
const text = from > 0 ? fs.readFileSync(process.argv[from + 1], "utf8") : await (await fetch(SOURCE)).text();
if (!text.includes("===BEGIN ICANN DOMAINS===") || !text.includes("===END PRIVATE DOMAINS===")) throw new Error("That is not the public suffix list.");

// A rule's labels as a browser sees them: "*" and "!" kept, IDN labels in punycode (URL hostnames are).
function ascii(rule) {
  const bang = rule.startsWith("!") ? "!" : "";
  const labels = rule.slice(bang.length).split(".").map((label) => (label === "*" ? "*" : url.domainToASCII(label)));
  if (labels.some((label) => !label)) throw new Error(`Cannot read the rule "${rule}".`);
  return bang + labels.join(".");
}

const rules = [];
for (const raw of text.split(/\r?\n/)) {
  const line = raw.trim().split(/\s/)[0];
  if (line && !line.startsWith("//")) rules.push(ascii(line.toLowerCase()));
}
const version = text.match(/^\/\/ VERSION: (.+)$/m)?.[1] ?? "unknown";
const commit = text.match(/^\/\/ COMMIT: (.+)$/m)?.[1] ?? "unknown";
const today = new Date().toISOString().slice(0, 10);

// One rule per line in a template string, so a refresh diffs line by line.
if (rules.some((rule) => /[`$\\]/.test(rule))) throw new Error("A rule would break the template string.");
const out = `// Generated by scripts/public-suffix-sync.mjs - do not edit by hand.
// Source: ${SOURCE} (ICANN + PRIVATE sections), fetched ${today}.
// List VERSION ${version}, COMMIT ${commit}. License: MPL-2.0 (https://mozilla.org/MPL/2.0/).
// One rule per line: "co.uk", "*.ck" (every label under ck), "!www.ck" (an exception). IDN in punycode.
export const PUBLIC_SUFFIX_RULES = \`
${rules.join("\n")}
\`;
`;
fs.writeFileSync(target, out);
console.log(`${rules.length} rules -> ${path.relative(process.cwd(), target)}`);
