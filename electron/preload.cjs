// The only bridge between the page and the vault. Each call maps to one ipcMain handler, registered through
// handle() in main.cjs or electron/ipc/*.cjs.
const { contextBridge, ipcRenderer } = require("electron");

const call = (channel) => (...args) => ipcRenderer.invoke(channel, ...args);

// Subscribes to a main-process event; returns the unsubscribe function.
const on = (channel, map = (...args) => args[0]) => (callback) => {
  const listener = (_event, ...args) => callback(map(...args));
  ipcRenderer.on(channel, listener);
  return () => ipcRenderer.removeListener(channel, listener);
};

